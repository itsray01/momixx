export function absoluteUrl(path = '/') {
  return new URL(path, site.url).toString()
}

/**
 * Per-page metadata with a self-referencing canonical URL. Every page must set
 * its own canonical, otherwise search engines may treat pages as duplicates.
 */
export function pageMetadata({ title, description, path }: { title: string; description: string; path: string }) {
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      title,
      description,
      url: path,
      siteName: site.legalName,
      type: 'website' as const,
      locale: 'en_SG',
      // Setting openGraph on a page replaces the root one, so re-attach the
      // shared social image generated by app/opengraph-image.tsx.
      images: [{ url: '/opengraph-image', width: 1200, height: 630, alt: `${site.name}: ${site.tagline}` }],
    },
  }
}
