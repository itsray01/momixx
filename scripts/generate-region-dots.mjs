// Regenerates components/regionDots.ts: land points for the South-East Asia dot map
// on the Locations and Contact pages.
//
//   npm install --no-save world-atlas topojson-client d3-geo
//   node scripts/generate-region-dots.mjs
//
// Samples a regular 0.3° grid over longitude 92° to 122° E and latitude 8° S to 22° N
// and keeps the points that fall on land in Natural Earth's 1:50m map (public domain).
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

// Keep in step with the bounding box in components/RegionMap.tsx.
const west = 92
const north = 22
const step = 0.3
const cols = 100 // 92° to 122° E
const rows = 100 // 22° N to 8° S

const round = (n) => Math.round(n * 100) / 100
const out = []
for (let r = 0; r <= rows; r++) {
  for (let c = 0; c <= cols; c++) {
    const lat = round(north - r * step)
    const lon = round(west + c * step)
    if (geoContains(land, [lon, lat])) out.push(lat, lon)
  }
}
writeFileSync(
  'components/regionDots.ts',
  `// Generated by scripts/generate-region-dots.mjs from Natural Earth (public domain) via
// world-atlas: land points on a 0.3° grid over 92° to 122° E and 8° S to 22° N, as flat
// [lat, lon, lat, lon, …] pairs. Regenerate rather than edit.
export const regionDots: readonly number[] = [${out.join(',')}]
`,
)
console.log(`${out.length / 2} land points`)
