// Regenerates components/regionMap.ts: the land outline, grid lines and pin positions for
// the South-East Asia map on the About and Contact pages.
//
//   npm install --no-save world-atlas topojson-client d3-geo
//   node scripts/generate-region-map.mjs
//
// Land is Natural Earth's 1:50m map (public domain), drawn as one shape with no country
// borders, in a Mercator projection fitted to longitude 93° to 123° E, latitude 3° S to 26.5° N.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoGraticule, geoMercator, geoPath } from 'd3-geo'

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

const width = 1000
const height = 860
const box = { type: 'Feature', geometry: { type: 'MultiPoint', coordinates: [[93, -3], [123, 26.5]] } }
const projection = geoMercator().fitExtent([[0, 0], [width, height]], box)
projection.clipExtent([[-4, -4], [width + 4, height + 4]])
const path = geoPath(projection).digits(1)

const sites = {
  singapore: [103.89, 1.33],
  penang: [100.41, 5.3],
  dongguan: [113.75, 23.02],
}
const pins = Object.fromEntries(
  Object.entries(sites).map(([key, lonLat]) => {
    const [x, y] = projection(lonLat)
    return [key, { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }]
  }),
)

const out = `// Generated by scripts/generate-region-map.mjs from Natural Earth 1:50m land (public domain). Do not edit by hand.
export const mapSize = { width: ${width}, height: ${height} }
export const landPath = ${JSON.stringify(path(land))}
export const gridPath = ${JSON.stringify(path(geoGraticule().step([5, 5])()))}
export const pinPoints = ${JSON.stringify(pins)} as const
`
writeFileSync(new URL('../components/regionMap.ts', import.meta.url), out)
console.log('wrote components/regionMap.ts', out.length, 'bytes', pins)
